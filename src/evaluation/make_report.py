"""Aggregate finished runs into reports/experiment_results.md (all numbers are read from files; nothing is typed in).

python -m src.evaluation.make_report [--out reports/experiment_results.md]
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

from src.evaluation.metrics import load_preds, paired_bootstrap, score

P = Path("outputs/preds")
RUNS = [  # (label, run, baseline it is compared against)
    ("Pretrained NLLB-1.3B (E0)", "baseline", None),
    ("LoRA r=8 (E1)", "lora_r8", "baseline"),
    ("LoRA r=16 (E2)", "lora_r16", "baseline"),
    ("LoRA r=8, 50% data (E3)", "lora_r8_f50", "baseline"),
    ("LoRA r=8, 25% data (E3)", "lora_r8_f25", "baseline"),
    ("LoRA r=8, 10% data (E3)", "lora_r8_f10", "baseline"),
    ("Pretrained NLLB-600M", "baseline_600m", None),
    ("Full fine-tune 600M (E4)", "full_ft", "baseline_600m"),
]


def have(run, name):
    return (P / f"{run}_{name}.jsonl").exists() and (P / f"{run}_{name}.metrics.json").exists()


def metrics(run, name):
    return json.loads((P / f"{run}_{name}.metrics.json").read_text())


def errors(run, name):
    f = P / f"{run}_{name}.errors.json"
    return json.loads(f.read_text()) if f.exists() else None


def meta(run, name):
    f = P / f"{run}_{name}.meta.json"
    return json.loads(f.read_text()) if f.exists() else None


def stats(run):
    f = Path("outputs") / run / "train_stats.json"
    return json.loads(f.read_text()) if f.exists() else None


def fmt(x, nd=2):
    return "n/a" if x is None else f"{x:.{nd}f}"


def delta_cell(run, base, name, cache):
    """'+x.xx [lo, hi]' paired-bootstrap 95% CI of chrF++ difference vs the baseline."""
    if base is None or not have(run, name) or not have(base, name):
        return ""
    key = (run, base, name)
    if key not in cache:
        _, hb, refs = load_preds(P / f"{base}_{name}.jsonl")
        _, hr, refs2 = load_preds(P / f"{run}_{name}.jsonl")
        assert refs == refs2, f"{run}/{base} {name}: different references"
        bs = paired_bootstrap(hb, hr, refs)
        cache[key] = f"{bs['mean_diff']:+.2f} [{bs['ci95'][0]:+.2f}, {bs['ci95'][1]:+.2f}]"
    return cache[key]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default="reports/experiment_results.md")
    out = ap.parse_args().out
    cache, L = {}, []
    L += ["# Experiment results", "", "Generated by `src.evaluation.make_report`. Every number is read from `outputs/`.",
          "Domain test = held-out Anuvaad **legal** en→ta (never used for training or model selection); General test = WMT24++ en→ta "
          "(social/literary/news/speech). Δ columns are the paired-bootstrap (1000 resamples) 95% interval of the chrF++ difference "
          "to the matching pretrained baseline.", ""]

    L += ["## Main results (chrF++ is the primary metric)", "",
          "| Method | Domain chrF++ | Δ vs baseline [95% CI] | General (WMT24++) chrF++ | Δ vs baseline [95% CI] | IN22-Gen chrF++ | Δ vs baseline [95% CI] | Domain BLEU | General BLEU | IN22-Gen BLEU |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for label, run, base in RUNS:
        if not have(run, "domain"):
            continue
        d, g = metrics(run, "domain"), (metrics(run, "general") if have(run, "general") else None)
        i = metrics(run, "in22") if have(run, "in22") else None
        L.append(f"| {label} | {fmt(d['chrf++'])} | {delta_cell(run, base, 'domain', cache)} | {fmt(g and g['chrf++'])} | "
                 f"{delta_cell(run, base, 'general', cache)} | {fmt(i and i['chrf++'])} | {delta_cell(run, base, 'in22', cache)} | "
                 f"{fmt(d['bleu'])} | {fmt(g and g['bleu'])} | {fmt(i and i['bleu'])} |")

    L += ["", "## Efficiency", "",
          "| Method | Trainable params | % of total | Train time (h) | Train examples | Peak train GPU mem (GB) | Inference s/sentence | Inference peak mem (GB) |",
          "|---|---|---|---|---|---|---|---|"]
    for label, run, _ in RUNS:
        st, m = stats(run), meta(run, "domain")
        if not (st or m):
            continue
        pr = st["params"] if st else None
        L.append(f"| {label} | {pr['trainable']:,} | {pr['pct']:.3f}% | {fmt(st['train_seconds'] / 3600)} | {st['train_examples']:,} | "
                 f"{fmt(st['peak_gpu_mem_gb'], 1)} | {fmt(m and m['sec_per_sentence'], 3)} | {fmt(m and m['peak_gpu_mem_gb'], 1)} |"
                 if pr else
                 f"| {label} | 0 (inference only) | - | - | - | - | {fmt(m and m['sec_per_sentence'], 3)} | {fmt(m and m['peak_gpu_mem_gb'], 1)} |")

    L += ["", "## Data efficiency (E3): LoRA r=8, domain test", "", "| Train fraction | Examples | Domain chrF++ | Δ vs baseline [95% CI] | General chrF++ |", "|---|---|---|---|---|"]
    for frac, run in (("0% (baseline)", "baseline"), ("10%", "lora_r8_f10"), ("25%", "lora_r8_f25"), ("50%", "lora_r8_f50"), ("100%", "lora_r8")):
        if have(run, "domain"):
            st = stats(run)
            L.append(f"| {frac} | {st['train_examples']:,} | {fmt(metrics(run, 'domain')['chrf++'])} | "
                     f"{delta_cell(run, 'baseline' if run != 'baseline' else None, 'domain', cache)} | "
                     f"{fmt(have(run, 'general') and metrics(run, 'general')['chrf++'])} |" if st else
                     f"| {frac} | 0 | {fmt(metrics(run, 'domain')['chrf++'])} | | {fmt(have(run, 'general') and metrics(run, 'general')['chrf++'])} |")

    L += ["", "## Heuristic error rates (fraction of test sentences flagged; see README for caveats)", "",
          "| Method | Set | Number mismatch | Untranslated / Latin | Copied source | Possible omission | Possible addition/repetition | Repetition loop | Empty |",
          "|---|---|---|---|---|---|---|---|---|"]
    for label, run, _ in RUNS:
        for name in ("domain", "general", "in22"):
            e = errors(run, name)
            if e:
                r = e["rates"]
                L.append(f"| {label} | {name} | " + " | ".join(f"{100 * r.get(k, 0):.2f}%" for k in (
                    "number_mismatch", "untranslated_or_latin", "copied_source", "possible_omission",
                    "possible_addition_or_repetition", "repetition_loop", "empty")) + " |")

    # general tests broken down by sub-domain
    for name, title in (("general", "WMT24++"), ("in22", "IN22-Gen")):
        L += ["", f"## {title} by sub-domain (chrF++)", ""]
        subs = defaultdict(dict)
        for label, run, _ in RUNS:
            if have(run, name):
                rows = [json.loads(l) for l in open(P / f"{run}_{name}.jsonl", encoding="utf-8")]
                by = defaultdict(lambda: ([], []))
                for r in rows:
                    by[r.get("domain")][0].append(r["hypothesis"]); by[r.get("domain")][1].append(r["reference"])
                for dom, (h, rf) in by.items():
                    subs[label][dom] = score(h, rf)["chrf++"]
        doms = sorted({d for v in subs.values() for d in v})
        if doms:
            L += ["| Method | " + " | ".join(doms) + " |", "|---|" + "---|" * len(doms)]
            for label, run, _ in RUNS:
                if label in subs:
                    L.append(f"| {label} | " + " | ".join(fmt(subs[label].get(d)) for d in doms) + " |")

    # independent (non-Anuvaad) legal check: IN22-Gen legal subset
    L += ["", "## Independent legal check: IN22-Gen legal subset (80 segments, not from Anuvaad)", "",
          "| Method | chrF++ | Baseline chrF++ | Δ [95% CI] |", "|---|---|---|---|"]
    def legal(run):
        x = [json.loads(l) for l in open(P / f"{run}_in22.jsonl", encoding="utf-8")]
        x = [r for r in x if r.get("domain") == "in22gen_legal"]
        return [r["hypothesis"] for r in x], [r["reference"] for r in x]
    for label, run, base in RUNS:
        if base and have(run, "in22") and have(base, "in22"):
            hb, rb = legal(base); hr, rr = legal(run); assert rb == rr
            bs = paired_bootstrap(hb, hr, rb)
            L.append(f"| {label} | {score(hr, rr)['chrf++']:.2f} | {score(hb, rb)['chrf++']:.2f} | "
                     f"{bs['mean_diff']:+.2f} [{bs['ci95'][0]:+.2f}, {bs['ci95'][1]:+.2f}] |")

    L += ["", "## Release-gate reports", ""] + [f"- `reports/release_{r}.md`" for _, r, b in RUNS if b and Path(f"reports/release_{r}.md").exists()]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
